def mm_to_m(mm):
    return mm / 1000

def m_to_mm(m):
    return m * 1000

def kg_to_lb(kg):
    return kg * 2.20462

def lb_to_kg(lb):
    return lb / 2.20462

def Nm_to_lbft(Nm):
    return Nm * 0.73756

def lbft_to_Nm(lbft):
    return lbft / 0.73756

def hp_to_kW(hp):
    return hp * 0.7457

def kW_to_hp(kW):
    return kW / 0.7457

def celsius_to_kelvin(C):
    return C + 273.15

def kelvin_to_celsius(K):
    return K - 273.15

def bar_to_psi(bar):
    return bar * 14.5038

def psi_to_bar(psi):
    return psi / 14.5038